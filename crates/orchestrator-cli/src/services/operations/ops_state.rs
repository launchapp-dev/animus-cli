    fn write_simple_archive(out: &Path, manifest_bytes: &[u8], entries: &[(PathBuf, Vec<u8>)]) {
        let file = File::create(out).unwrap();
        let encoder = zstd::stream::write::Encoder::new(BufWriter::new(file), 1).unwrap().auto_finish();
        let mut builder = Builder::new(encoder);
        append_bytes(&mut builder, Path::new(MANIFEST_FILENAME), manifest_bytes).unwrap();
        for (path, contents) in entries {
            append_bytes(&mut builder, path, contents).unwrap();
        }
        builder.finish().unwrap();
    }

    fn archive_entries(archive: &Path) -> Vec<String> {
        let file = File::open(archive).unwrap();
        let decoder = zstd::stream::read::Decoder::new(BufReader::new(file)).unwrap();
        let mut tar = Archive::new(decoder);
        tar.entries()
            .unwrap()
            .filter_map(Result::ok)
            .map(|e| e.path().unwrap().into_owned().to_string_lossy().to_string())
            .collect()
    }
