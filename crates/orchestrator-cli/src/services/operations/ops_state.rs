/// Walk a staged scope payload looking for at least one regular file.
/// Returns `Ok(false)` for a tree of empty dirs, `Ok(true)` as soon as
/// any file is found, and propagates IO errors. Used as the swap-gate
/// guard — we never want to replace live state with a directory tree
/// that has no actual files.
fn staged_scope_contains_file(root: &Path) -> Result<bool> {
    let read = std::fs::read_dir(root).with_context(|| format!("read_dir {}", root.display()))?;
    for entry in read {
        let entry = entry.with_context(|| format!("read entry under {}", root.display()))?;
        let ft = entry.file_type().with_context(|| format!("stat {}", entry.path().display()))?;
        if ft.is_file() {
            return Ok(true);
        }
        if ft.is_dir() && staged_scope_contains_file(&entry.path())? {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Names a freshly-created scope dir contains by default (markers,
/// origin pointers). If a scope dir only contains these, treat it as
/// empty for export-purposes — there is no real state to back up.
const SCOPE_BOOTSTRAP_FILENAMES: &[&str] = &[".project-root", ".git-origin"];

fn scope_dir_has_real_state(path: &Path) -> bool {
    match std::fs::read_dir(path) {
        Ok(read) => {
            for entry in read.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if !SCOPE_BOOTSTRAP_FILENAMES.contains(&name.as_str()) {
                    return true;
                }
            }
            false
        }
        Err(_) => false,
    }
}

/// Non-mutating scope-dir lookup. Prefers the hash-derived directory
/// when it exists, otherwise searches `~/.animus` for an existing
/// same-origin scope without writing markers (unlike
/// `protocol::scoped_state_root`, which would create files). Falls
/// back to the hash-derived path even if it does not yet exist; the
/// caller is responsible for refusing to act on a non-existent scope.
fn resolve_existing_scope_dir(project_root: &Path) -> (String, PathBuf) {
    let hash_name = repository_scope_for_path(project_root);
    let Some(home) = dirs::home_dir() else {
        return (hash_name.clone(), PathBuf::from(".animus").join(&hash_name));
    };
    let ao_root = home.join(".animus");
    let primary = ao_root.join(&hash_name);
    if primary.exists() {
        return (hash_name, primary);
    }
    if let Some(adopted) = find_adopted_scope_dir(&ao_root, project_root) {
        if let Some(name) = adopted.file_name().and_then(|n| n.to_str()).map(str::to_string) {
            return (name, adopted);
        }
    }
    (hash_name, primary)
}

fn find_adopted_scope_dir(ao_root: &Path, project_root: &Path) -> Option<PathBuf> {
    let origin = git_remote_origin(project_root)?;
    let canonical = project_root.canonicalize().unwrap_or_else(|_| project_root.to_path_buf());
    let entries = std::fs::read_dir(ao_root).ok()?;
    for entry in entries.flatten() {
        let scope_dir = entry.path();
        if !scope_dir.is_dir() {
            continue;
        }
        let Ok(existing_origin) = std::fs::read_to_string(scope_dir.join(".git-origin")) else {
            continue;
        };
        if existing_origin.trim() != origin {
            continue;
        }
        match std::fs::read_to_string(scope_dir.join(".project-root")) {
            Ok(existing_root) => {
                let recorded = Path::new(existing_root.trim());
                match recorded.canonicalize() {
                    Ok(existing_canonical) if existing_canonical == canonical => return Some(scope_dir),
                    Ok(_) => continue,
                    Err(_) => return Some(scope_dir),
                }
            }
            Err(_) => return Some(scope_dir),
        }
    }
    None
}

fn git_remote_origin(project_root: &Path) -> Option<String> {
    std::process::Command::new("git")
        .args(["remote", "get-url", "origin"])
        .current_dir(project_root)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::null())
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
}

/// A scope id always comes from `repository_scope_for_path`, which
/// emits `<slug>-<12-hex>` with characters in `[a-z0-9-]`. Reject
/// anything else — we treat the scope name as a single path component
/// and don't want a crafted MANIFEST.json escaping `~/.animus`.
fn validate_scope_name(scope: &str) -> Result<()> {
    if scope.is_empty() {
        return Err(invalid_input_error(
            "exported state manifest is invalid: repo_scope is required — check MANIFEST.json in the archive",
        ));
    }
    for ch in scope.chars() {
        match ch {
            'a'..='z' | '0'..='9' | '-' => {}
            _ => {
                return Err(invalid_input_error(format!(
                    "manifest repo_scope {scope:?} contains illegal character {ch:?}; refusing import"
                )));
            }
        }
    }
    Ok(())
}

