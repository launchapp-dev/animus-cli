const EXPORT_SCHEMA_V1: &str = "animus.state.export.v1";
const MANIFEST_FILENAME: &str = "MANIFEST.json";
const PRINCIPALS_ARCHIVE_PATH: &str = "global/principals.yaml";
const SCOPE_ARCHIVE_PREFIX: &str = "scope/";
const ZSTD_LEVEL: i32 = 3;

/// Files inside `daemon/` that are pure runtime state (locks, logs,
/// pid files, sockets). They are excluded from the default export
/// scope so a restore on a different machine doesn't fight with the
/// running daemon. The user can still capture the full scope by
/// archiving manually if they really want to.
const DAEMON_RUNTIME_FILES: &[&str] = &["daemon.lock", "daemon.log", "daemon.pid", "control.sock"];

/// Top-level entries in the scope dir we exclude from the default
/// export. These are either ephemeral runtime artifacts (sockets,
/// lock files, log streams) or directories handled by their own
/// opt-in flags (`runs/`, `artifacts/`).
const SCOPE_TOPLEVEL_EXCLUDES: &[&str] = &[
    "control.sock",
    "core-state.lock",
    "daemon",
    "config",
    "runs",
    "artifacts",
    "worktrees",
    // Bootstrap markers: `.project-root` carries the user's absolute
    // source path (useless / wrong on another machine and in a
    // re-scope) and `.git-origin` carries the raw remote URL, which
    // can embed a `token@host` credential. Both are regenerated by
    // the runtime on next access; skipping them in the archive keeps
    // backups portable AND avoids leaking credentials via the
    // remote-URL form.
    ".project-root",
    ".git-origin",
];

/// File-extension blocklist for top-level scope files. Picks up lock /
/// socket / pid files we'd otherwise capture by accident.
const SCOPE_TOPLEVEL_EXCLUDE_EXTENSIONS: &[&str] = &["lock", "sock", "pid"];

/// Tokens that look like secrets when they appear as JSON keys. If a
/// state JSON file carries any of these we refuse the export — secrets
/// belong in a per-machine keychain, not a portable backup archive.
const SECRET_KEY_TOKENS: &[&str] = &["token", "secret", "api_key", "apikey", "password", "passphrase", "credential"];

#[derive(Debug, Serialize, Deserialize)]
struct Manifest {
    schema: String,
    exported_at: String,
    animus_version: String,
    repo_scope: String,
    include_runs: bool,
    include_artifacts: bool,
    file_count: u64,
    total_bytes_uncompressed: u64,
}

#[derive(Debug, Serialize)]
struct ExportResult {
    schema: &'static str,
    archive: PathBuf,
    repo_scope: String,
    file_count: u64,
    total_bytes_uncompressed: u64,
    include_runs: bool,
    include_artifacts: bool,
    principals_yaml_included: bool,
}

#[derive(Debug, Serialize)]
struct ImportResult {
    schema: &'static str,
    archive: PathBuf,
    target_scope_dir: PathBuf,
    repo_scope_source: String,
    repo_scope_target: String,
    file_count: u64,
    snapshot_dir: Option<PathBuf>,
    principals_overwritten: bool,
}

pub(crate) async fn handle_state(command: StateCommand, project_root: &str, json: bool) -> Result<()> {
    match command {
        StateCommand::Export(args) => handle_export(args, project_root, json),
        StateCommand::Import(args) => handle_import(args, project_root, json),
    }
}

fn handle_export(args: StateExportArgs, project_root: &str, json: bool) -> Result<()> {
    let project_root_path = Path::new(project_root);
    // Resolve the scope dir WITHOUT mutating disk. `scoped_state_root`
    // would create the dir + marker files on a fresh project and let
    // us emit a marker-only archive — exactly the empty-state case we
    // want to refuse. Use a read-only lookup that prefers a same-origin
    // adopted scope when available.
    let (scope, scope_dir) = resolve_existing_scope_dir(project_root_path);
    if !scope_dir.exists() || !scope_dir_has_real_state(&scope_dir) {
        return Err(not_found_error(format!(
            "no scoped state at {} — nothing to export. Run an Animus command in this project first.",
            scope_dir.display()
        )));
    }

    let exported_at = Utc::now();
    let out_path = match args.out {
        Some(path) => PathBuf::from(path),
        None => default_export_path(&scope, &exported_at),
    };

    if let Some(parent) = out_path.parent() {
        if !parent.as_os_str().is_empty() && !parent.exists() {
            std::fs::create_dir_all(parent)
                .with_context(|| format!("create parent dir for archive at {}", parent.display()))?;
        }
    }

    let entries = collect_export_entries(&scope_dir, args.include_runs, args.include_artifacts)?;
    scan_entries_for_secrets(&entries)?;

    let principals_path = principals_path();
    let principals_included = principals_path.exists();

    let mut total_bytes: u64 = 0;
    let mut file_count: u64 = 0;
    for entry in &entries {
        let meta =
            std::fs::metadata(&entry.source).with_context(|| format!("stat {} for export", entry.source.display()))?;
        if meta.is_file() {
            total_bytes += meta.len();
            file_count += 1;
        }
    }
    if principals_included {
        let meta = std::fs::metadata(&principals_path)
            .with_context(|| format!("stat principals.yaml at {}", principals_path.display()))?;
        total_bytes += meta.len();
        file_count += 1;
    }

    let manifest = Manifest {
        schema: EXPORT_SCHEMA_V1.to_string(),
        exported_at: exported_at.to_rfc3339(),
        animus_version: env!("CARGO_PKG_VERSION").to_string(),
        repo_scope: scope.clone(),
        include_runs: args.include_runs,
        include_artifacts: args.include_artifacts,
        file_count,
        total_bytes_uncompressed: total_bytes,
    };
    let manifest_bytes = serde_json::to_vec_pretty(&manifest).context("serialize MANIFEST.json")?;

    write_archive(&out_path, &manifest_bytes, &entries, principals_included.then_some(&principals_path))?;

    let result = ExportResult {
        schema: EXPORT_SCHEMA_V1,
        archive: out_path,
        repo_scope: scope,
        file_count,
        total_bytes_uncompressed: total_bytes,
        include_runs: args.include_runs,
        include_artifacts: args.include_artifacts,
        principals_yaml_included: principals_included,
    };
    print_value(result, json)
}

fn handle_import(args: StateImportArgs, project_root: &str, json: bool) -> Result<()> {
    let archive_path = PathBuf::from(&args.archive);
    if !archive_path.exists() {
        return Err(not_found_error(format!("archive not found at {}", archive_path.display())));
    }

    let manifest = read_manifest(&archive_path)?;
    if manifest.schema != EXPORT_SCHEMA_V1 {
        return Err(invalid_input_error(format!(
            "unsupported export schema {:?} — this animus build only loads {}; upgrade animus and retry",
            manifest.schema, EXPORT_SCHEMA_V1
        )));
    }

    let target_scope = match args.into_project.as_deref() {
        Some(path) => repository_scope_for_path(Path::new(path)),
        None => manifest.repo_scope.clone(),
    };
    // TODO(codex-p2): When `--into-project` differs from the source
    // scope, task records in the staged `core-state.json` can still
    // carry absolute `worktree_path` values rooted at the source
    // scope. The dispatcher rejects tasks whose recorded worktree
    // lives outside the target's managed worktree root, so imported
    // tasks become unrunnable until `animus subject status … --status
    // ready` clears the path. Rewriting these paths in-place during
    // re-scope is the right fix but requires plugin-state knowledge
    // we don't have at this layer — tracked for v0.5.9.
    // The manifest is untrusted. Validate before we let it influence
    // any path on disk so a crafted `repo_scope` like `../../escape`
    // can't make us write outside `~/.animus`.
    validate_scope_name(&target_scope)?;
    let _ = project_root;
    let target_scope_dir = scope_dir_for(&target_scope);
    let ao_root = animus_home()?;
    std::fs::create_dir_all(&ao_root).with_context(|| format!("create ao root at {}", ao_root.display()))?;

    let target_non_empty = scope_dir_is_nonempty(&target_scope_dir);
    if target_non_empty && !args.yes {
        return Err(conflict_error(format!(
            "target scope {} already has state; re-run with --yes to overwrite (a safety snapshot will be taken first)",
            target_scope_dir.display()
        )));
    }

    let timestamp = Utc::now().format("%Y%m%d%H%M%S").to_string();
    let staging_dir = ao_root.join(format!("{target_scope}.import-staging-{timestamp}"));
    if staging_dir.exists() {
        std::fs::remove_dir_all(&staging_dir)
            .with_context(|| format!("clear stale staging dir {}", staging_dir.display()))?;
    }
    std::fs::create_dir_all(&staging_dir).with_context(|| format!("create staging dir {}", staging_dir.display()))?;

    let extract =
        extract_archive(&archive_path, &staging_dir).context("extract archive into staging dir").inspect_err(|_| {
            let _ = std::fs::remove_dir_all(&staging_dir);
        })?;

    // Validate the staged payload BEFORE touching anything live —
    // neither the scope dir nor principals.yaml. A corrupt or empty
    // archive must never move the existing scope aside or write a new
    // RBAC root-of-trust just to fail seconds later.
    let staged_scope_payload = staging_dir.join("scope");
    if !staged_scope_payload.exists() {
        let _ = std::fs::remove_dir_all(&staging_dir);
        return Err(invalid_input_error(
            "archive does not contain a `scope/` payload — refusing to import an empty scope".to_string(),
        ));
    }
    let staged_meta = std::fs::symlink_metadata(&staged_scope_payload)
        .with_context(|| format!("stat staged scope payload at {}", staged_scope_payload.display()))?;
    if !staged_meta.file_type().is_dir() {
        let _ = std::fs::remove_dir_all(&staging_dir);
        return Err(conflict_error(format!(
            "staged scope payload at {} is not a directory — refusing import",
            staged_scope_payload.display()
        )));
    }
    // An empty `scope/` directory — or a directory tree with no real
    // files — shouldn't be allowed to clobber live state. Replacing a
    // non-empty scope with nothing is the worst possible failure mode
    // for a restore command, and an archive that only declares empty
    // subdirectories under `scope/` is functionally identical to one
    // with no payload at all.
    if !staged_scope_contains_file(&staged_scope_payload)? {
        let _ = std::fs::remove_dir_all(&staging_dir);
        return Err(invalid_input_error(
            "archive `scope/` directory contains no files — refusing to replace live state with empty payload"
                .to_string(),
        ));
    }

    // Plan the principals action up front. If we'd need
    // `--yes-overwrite-principals` and the user didn't pass it, refuse
    // NOW — before the live scope is moved. This is the load-bearing
    // safety property: a denied principals overwrite must never leave
    // the project with a half-restored scope.
    let principals_plan = plan_principals_action(&extract, args.yes_overwrite_principals).inspect_err(|_| {
        let _ = std::fs::remove_dir_all(&staging_dir);
    })?;

    let snapshot_dir = if target_non_empty {
        let snap = ao_root.join(format!("{target_scope}.backup-pre-import-{timestamp}"));
        std::fs::rename(&target_scope_dir, &snap).map_err(|err| {
            let _ = std::fs::remove_dir_all(&staging_dir);
            internal_error(format!("failed to snapshot existing scope to {}: {err}", snap.display()))
        })?;
        Some(snap)
    } else {
        if target_scope_dir.exists() {
            std::fs::remove_dir_all(&target_scope_dir).map_err(|err| {
                let _ = std::fs::remove_dir_all(&staging_dir);
                internal_error(format!("failed to clear empty scope dir {}: {err}", target_scope_dir.display()))
            })?;
        }
        None
    };

    if let Err(err) = std::fs::rename(&staged_scope_payload, &target_scope_dir) {
        // Best-effort rollback: put the snapshot back where the live
        // scope used to be so the project remains bootable. If this
        // rollback fails, surface both errors.
        if let Some(snap) = snapshot_dir.as_ref() {
            let _ = std::fs::rename(snap, &target_scope_dir);
        }
        let _ = std::fs::remove_dir_all(&staging_dir);
        return Err(internal_error(format!(
            "atomic swap failed (staging={}, target={}): {err}",
            staged_scope_payload.display(),
            target_scope_dir.display()
        )));
    }

    // Scope swap succeeded — only NOW touch principals.yaml. Any
    // failure here is from raw IO, not policy: the policy gate
    // (`plan_principals_action`) was checked before the swap.
    let principals_overwritten = apply_principals_action(&extract, principals_plan).inspect_err(|_| {
        let _ = std::fs::remove_dir_all(&staging_dir);
    })?;

    let _ = std::fs::remove_dir_all(&staging_dir);

    let result = ImportResult {
        schema: EXPORT_SCHEMA_V1,
        archive: archive_path,
        target_scope_dir,
        repo_scope_source: manifest.repo_scope,
        repo_scope_target: target_scope,
        file_count: manifest.file_count,
        snapshot_dir,
        principals_overwritten,
    };
    print_value(result, json)
}

struct ExportEntry {
    source: PathBuf,
    archive_relative: PathBuf,
}

fn collect_export_entries(scope_dir: &Path, include_runs: bool, include_artifacts: bool) -> Result<Vec<ExportEntry>> {
    let mut entries = Vec::new();
    let config_dir = scope_dir.join("config");
    if config_dir.is_dir() {
        walk_into(&config_dir, scope_dir, &mut entries, |_| true)?;
    }
    let daemon_dir = scope_dir.join("daemon");
    if daemon_dir.is_dir() {
        walk_into(&daemon_dir, scope_dir, &mut entries, |path| {
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default();
            !DAEMON_RUNTIME_FILES.contains(&name)
        })?;
    }

    // Top-level scope state outside config/ and daemon/: things like
    // `core-state.json`, `resume-config.json`, `workflow.db`,
    // `audit.jsonl`, `state/`, `docs/`, `metrics/`, `logs/`, plus the
    // migration / column marker files. These are the load-bearing
    // pieces of a restore — leaving them out makes the archive useless
    // for actual disaster recovery.
    let read = std::fs::read_dir(scope_dir).with_context(|| format!("read_dir {}", scope_dir.display()))?;
    for entry in read {
        let entry = entry.with_context(|| format!("read entry under {}", scope_dir.display()))?;
        let path = entry.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or_default().to_string();
        if SCOPE_TOPLEVEL_EXCLUDES.contains(&name.as_str()) {
            continue;
        }
        if let Some(ext) = path.extension().and_then(|e| e.to_str()) {
            if SCOPE_TOPLEVEL_EXCLUDE_EXTENSIONS.contains(&ext) {
                continue;
            }
        }
        let ft = entry.file_type().with_context(|| format!("stat {}", path.display()))?;
        if ft.is_symlink() {
            continue;
        }
        if ft.is_dir() {
            walk_into(&path, scope_dir, &mut entries, |_| true)?;
        } else if ft.is_file() {
            let rel = path
                .strip_prefix(scope_dir)
                .map(|p| p.to_path_buf())
                .with_context(|| format!("strip prefix {} from {}", scope_dir.display(), path.display()))?;
            entries.push(ExportEntry { source: path, archive_relative: rel });
        }
    }

    if include_runs {
        let runs_dir = scope_dir.join("runs");
        if runs_dir.is_dir() {
            walk_into(&runs_dir, scope_dir, &mut entries, |_| true)?;
        }
    }
    if include_artifacts {
        let artifacts_dir = scope_dir.join("artifacts");
        if artifacts_dir.is_dir() {
            walk_into(&artifacts_dir, scope_dir, &mut entries, |_| true)?;
        }
    }
    Ok(entries)
}

fn walk_into(
    root: &Path,
    scope_dir: &Path,
    out: &mut Vec<ExportEntry>,
    keep: impl Fn(&Path) -> bool + Copy,
) -> Result<()> {
    let read = std::fs::read_dir(root).with_context(|| format!("read_dir {}", root.display()))?;
    for entry in read {
        let entry = entry.with_context(|| format!("read entry under {}", root.display()))?;
        let path = entry.path();
        if !keep(&path) {
            continue;
        }
        let ft = entry.file_type().with_context(|| format!("stat {}", path.display()))?;
        if ft.is_symlink() {
            continue;
        }
        if ft.is_dir() {
            walk_into(&path, scope_dir, out, keep)?;
        } else if ft.is_file() {
            let rel = path
                .strip_prefix(scope_dir)
                .map(|p| p.to_path_buf())
                .with_context(|| format!("strip prefix {} from {}", scope_dir.display(), path.display()))?;
            out.push(ExportEntry { source: path, archive_relative: rel });
        }
    }
    Ok(())
}

fn scan_entries_for_secrets(entries: &[ExportEntry]) -> Result<()> {
    for entry in entries {
        let name = entry.source.file_name().and_then(|n| n.to_str()).unwrap_or_default();
        if name.eq_ignore_ascii_case(".env") || name.starts_with(".env.") {
            return Err(conflict_error(format!(
                "refusing to export likely secret file {} — move it outside the scope dir or scrub it first",
                entry.source.display()
            )));
        }
        if entry.source.extension().and_then(|e| e.to_str()) != Some("json") {
            continue;
        }
        let bytes = match std::fs::read(&entry.source) {
            Ok(b) => b,
            Err(_) => continue,
        };
        let value: serde_json::Value = match serde_json::from_slice(&bytes) {
            Ok(v) => v,
            Err(_) => continue,
        };
        if let Some(hit) = find_secret_key(&value) {
            return Err(conflict_error(format!(
                "refusing to export {}: contains key {:?} that looks like a secret. Scrub the field or move credentials to a keychain plugin.",
                entry.source.display(),
                hit
            )));
        }
    }
    Ok(())
}

fn find_secret_key(value: &serde_json::Value) -> Option<String> {
    match value {
        serde_json::Value::Object(map) => {
            for (k, v) in map {
                if looks_like_secret_field(k, v) {
                    return Some(k.clone());
                }
                if let Some(hit) = find_secret_key(v) {
                    return Some(hit);
                }
            }
            None
        }
        serde_json::Value::Array(items) => items.iter().find_map(find_secret_key),
        _ => None,
    }
}

/// A field is treated as a credential only when BOTH:
///   * the key name contains one of `SECRET_KEY_TOKENS` (after
///     lowercasing), AND
///   * the value is a non-empty string of plausible credential length.
///
/// This intentionally lets numeric counters slide through —
/// `cost-state.v1.json` carries `total_tokens: 42` that the previous
/// rule treated as a secret, blocking ordinary backups.
fn looks_like_secret_field(key: &str, value: &serde_json::Value) -> bool {
    let lower = key.to_ascii_lowercase();
    if !SECRET_KEY_TOKENS.iter().any(|tok| lower.contains(tok)) {
        return false;
    }
    let Some(s) = value.as_str() else {
        return false;
    };
    let trimmed = s.trim();
    if trimmed.is_empty() {
        return false;
    }
    // Credentials are typically opaque tokens — ≥12 chars and not a
    // bare integer. Short or numeric values are almost always counters
    // (`tokens_used: "12"`) or descriptive labels rather than secrets.
    if trimmed.len() < 12 {
        return false;
    }
    if trimmed.chars().all(|c| c.is_ascii_digit()) {
        return false;
    }
    true
}

fn write_archive(
    out_path: &Path,
    manifest_bytes: &[u8],
    entries: &[ExportEntry],
    principals: Option<&Path>,
) -> Result<()> {
    let tmp = with_suffix(out_path, ".partial");
    if tmp.exists() {
        std::fs::remove_file(&tmp).with_context(|| format!("remove stale tmp at {}", tmp.display()))?;
    }
    let file = File::create(&tmp).with_context(|| format!("create archive at {}", tmp.display()))?;
    let encoder =
        zstd::stream::write::Encoder::new(BufWriter::new(file), ZSTD_LEVEL).context("init zstd encoder")?.auto_finish();
    let mut builder = Builder::new(encoder);

    append_bytes(&mut builder, Path::new(MANIFEST_FILENAME), manifest_bytes)?;

    for entry in entries {
        let archive_path = PathBuf::from(SCOPE_ARCHIVE_PREFIX).join(&entry.archive_relative);
        append_file(&mut builder, &archive_path, &entry.source)?;
    }
    if let Some(principals) = principals {
        append_file(&mut builder, Path::new(PRINCIPALS_ARCHIVE_PATH), principals)?;
    }

    builder.finish().context("finalize tar")?;
    drop(builder);

    std::fs::rename(&tmp, out_path)
        .with_context(|| format!("atomically move archive into place at {}", out_path.display()))?;
    Ok(())
}

fn append_bytes<W: Write>(builder: &mut Builder<W>, archive_path: &Path, bytes: &[u8]) -> Result<()> {
    let mut header = Header::new_gnu();
    header.set_size(bytes.len() as u64);
    header.set_mode(0o644);
    header.set_entry_type(EntryType::Regular);
    header.set_mtime(Utc::now().timestamp().max(0) as u64);
    header.set_path(archive_path).with_context(|| format!("set tar entry path {}", archive_path.display()))?;
    header.set_cksum();
    builder.append(&header, bytes).with_context(|| format!("append tar entry {}", archive_path.display()))?;
    Ok(())
}

fn append_file<W: Write>(builder: &mut Builder<W>, archive_path: &Path, source: &Path) -> Result<()> {
    let meta = std::fs::metadata(source).with_context(|| format!("stat {}", source.display()))?;
    let mut header = Header::new_gnu();
    header.set_metadata(&meta);
    header.set_path(archive_path).with_context(|| format!("set tar entry path {}", archive_path.display()))?;
    header.set_cksum();
    let file = File::open(source).with_context(|| format!("open {}", source.display()))?;
    builder
        .append(&header, BufReader::new(file))
        .with_context(|| format!("append tar entry {}", archive_path.display()))?;
    Ok(())
}

fn read_manifest(archive_path: &Path) -> Result<Manifest> {
    let file = File::open(archive_path).with_context(|| format!("open archive at {}", archive_path.display()))?;
    let decoder = zstd::stream::read::Decoder::new(BufReader::new(file)).context("init zstd decoder")?;
    let mut archive = Archive::new(decoder);
    for entry in archive.entries().context("iterate tar entries")? {
        let mut entry = entry.context("read tar entry")?;
        let path = entry.path().context("decode entry path")?.into_owned();
        if path == Path::new(MANIFEST_FILENAME) {
            let mut buf = Vec::new();
            entry.read_to_end(&mut buf).context("read MANIFEST.json from archive")?;
            let manifest: Manifest = serde_json::from_slice(&buf).context("parse MANIFEST.json from archive")?;
            return Ok(manifest);
        }
    }
    Err(invalid_input_error(
        "archive is missing MANIFEST.json — not a valid animus.state.export.v1 archive".to_string(),
    ))
}

struct ExtractOutcome {
    staged_principals: Option<PathBuf>,
}

fn extract_archive(archive_path: &Path, staging_dir: &Path) -> Result<ExtractOutcome> {
    let file = File::open(archive_path).with_context(|| format!("open archive at {}", archive_path.display()))?;
    let decoder = zstd::stream::read::Decoder::new(BufReader::new(file)).context("init zstd decoder")?;
    let mut archive = Archive::new(decoder);
    let mut staged_principals = None;
    for entry in archive.entries().context("iterate tar entries")? {
        let mut entry = entry.context("read tar entry")?;
        let raw_path = entry.path().context("decode entry path")?.into_owned();
        if raw_path == Path::new(MANIFEST_FILENAME) {
            continue;
        }
        if !is_safe_archive_path(&raw_path) {
            return Err(conflict_error(format!(
                "refusing to extract suspicious archive path {:?} (absolute or contains ..)",
                raw_path.display()
            )));
        }
        // Reject everything except regular files and directories
        // before we touch the filesystem. An exported archive only
        // ever contains those two kinds, so symlink / hardlink / char
        // device / fifo entries can only come from a tampered or
        // hand-rolled archive trying to escape the staging dir.
        let entry_type = entry.header().entry_type();
        if !(entry_type.is_file() || entry_type.is_dir()) {
            return Err(conflict_error(format!(
                "refusing to extract tar entry {:?} of type {:?}; archives may contain only regular files and directories",
                raw_path.display(),
                entry_type,
            )));
        }
        let dest = staging_dir.join(&raw_path);
        if let Some(parent) = dest.parent() {
            std::fs::create_dir_all(parent).with_context(|| format!("create parent {}", parent.display()))?;
        }
        if entry_type.is_dir() {
            std::fs::create_dir_all(&dest).with_context(|| format!("create directory entry {}", dest.display()))?;
            continue;
        }
        // Refuse to write through an existing symlink at `dest`.
        // `entry.unpack` calls `File::create`, which would follow a
        // pre-existing symlink left behind by a stale staging dir.
        if let Ok(meta) = std::fs::symlink_metadata(&dest) {
            if meta.file_type().is_symlink() {
                return Err(conflict_error(format!(
                    "refusing to write through pre-existing symlink at {}",
                    dest.display(),
                )));
            }
        }
        entry.unpack(&dest).with_context(|| format!("unpack tar entry to {}", dest.display()))?;
        // Final sanity check: the file we just wrote must be a regular
        // file, not a symlink the tar crate decided to honour.
        let meta =
            std::fs::symlink_metadata(&dest).with_context(|| format!("stat extracted entry {}", dest.display()))?;
        if !meta.file_type().is_file() {
            return Err(conflict_error(format!(
                "extracted entry at {} is not a regular file ({:?})",
                dest.display(),
                meta.file_type(),
            )));
        }
        if raw_path == Path::new(PRINCIPALS_ARCHIVE_PATH) {
            staged_principals = Some(dest);
        }
    }
    Ok(ExtractOutcome { staged_principals })
}

fn is_safe_archive_path(path: &Path) -> bool {
    if path.is_absolute() {
        return false;
    }
    for component in path.components() {
        match component {
            std::path::Component::Normal(_) => {}
            std::path::Component::CurDir => {}
            _ => return false,
        }
    }
    true
}

/// What `handle_principals_file` plans to do. Computed BEFORE the
/// live scope swap so we can fail early when the caller didn't
/// opt-in to RBAC changes, without leaving the scope half-restored.
enum PrincipalsPlan {
    NoStaged,
    NoChange,
    InstallNew,
    Overwrite,
}

/// Compute the principals action without mutating disk. Returns an
/// error when the planned action requires `--yes-overwrite-principals`
/// and the caller didn't pass it.
fn plan_principals_action(extract: &ExtractOutcome, allow_overwrite: bool) -> Result<PrincipalsPlan> {
    let Some(staged) = extract.staged_principals.as_ref() else {
        return Ok(PrincipalsPlan::NoStaged);
    };
    let target = principals_path();
    if !target.exists() {
        return Ok(PrincipalsPlan::InstallNew);
    }
    let existing =
        std::fs::read(&target).with_context(|| format!("read existing principals.yaml at {}", target.display()))?;
    let incoming =
        std::fs::read(staged).with_context(|| format!("read staged principals.yaml at {}", staged.display()))?;
    if existing == incoming {
        return Ok(PrincipalsPlan::NoChange);
    }
    if !allow_overwrite {
        return Err(conflict_error(format!(
            "archive principals.yaml differs from existing {} — re-run with --yes-overwrite-principals to replace RBAC config",
            target.display()
        )));
    }
    Ok(PrincipalsPlan::Overwrite)
}

/// Principals.yaml is the RBAC root-of-trust. It must NEVER be silently
/// overwritten, even when `--yes` accepts clobbering the scope dir.
/// Touching it requires a separate explicit opt-in
/// (`--yes-overwrite-principals`), which `plan_principals_action`
/// already validated.
fn apply_principals_action(extract: &ExtractOutcome, plan: PrincipalsPlan) -> Result<bool> {
    match plan {
        PrincipalsPlan::NoStaged | PrincipalsPlan::NoChange => Ok(false),
        PrincipalsPlan::InstallNew => {
            let Some(staged) = extract.staged_principals.as_ref() else {
                return Ok(false);
            };
            let target = principals_path();
            if let Some(parent) = target.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("create parent for principals.yaml at {}", parent.display()))?;
            }
            std::fs::copy(staged, &target)
                .with_context(|| format!("install principals.yaml at {}", target.display()))?;
            Ok(true)
        }
        PrincipalsPlan::Overwrite => {
            let Some(staged) = extract.staged_principals.as_ref() else {
                return Ok(false);
            };
            let target = principals_path();
            let backup = with_suffix(&target, &format!(".backup-{}", Utc::now().format("%Y%m%d%H%M%S")));
            std::fs::copy(&target, &backup)
                .with_context(|| format!("snapshot existing principals.yaml to {}", backup.display()))?;
            std::fs::copy(staged, &target)
                .with_context(|| format!("overwrite principals.yaml at {}", target.display()))?;
            Ok(true)
        }
    }
}

